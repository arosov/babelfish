"""Fast replay regression test: the committed capture JSON is the frozen
red/green signal for Ghost composition.

The capture (tests/fixtures/dictation_fr_capture.json) is regenerated by
the slow replay test (tests/test_replay_pipeline.py, GPU) by replaying
tests/fixtures/dictation_fr.wav through the real pipeline. This test
replays the committed capture through GhostComposer alone — no model, no
GPU, seconds-fast — and asserts the composed line does not duplicate:

(a) total composed words <= true words x 1.3;
(b) no normalized word is repeated beyond its true count + 1 (with a
    floor of 2 for legitimate model re-wording variants);
(c) append-only: committed words never shrink across frames except the
    bounded dedup trim;
(d) the opening words of each utterance's composed line are preserved
    to the end of the utterance (losing the opening is the observed
    failure mode).

The reference text is used for sanity bounds only — never exact-match
asserts; the model output will differ (see the rework plan).
"""

import json
import unicodedata
from collections import Counter
from pathlib import Path

from babelfish_stt.ghost_composer import GhostComposer, _norm_word

CAPTURE_PATH = Path(__file__).parent / "fixtures" / "dictation_fr_capture.json"


def _fold(word: str) -> str:
    """Accent- and case-insensitive word form for fuzzy comparison only
    (the model re-spells accents across frames: 'médiathèque' ->
    'Mediathèque'). The composer itself keeps raw words."""
    decomposed = unicodedata.normalize("NFD", word.lower())
    stripped = "".join(c for c in decomposed if not unicodedata.combining(c))
    return _norm_word(stripped)

# Reference text for the fixture dictation (fuzzy bounds only).
REFERENCE_TEXT = (
    "La médiathèque Centre-ville est installée depuis 1925 dans les locaux "
    "d'une ancienne école de pré-apprentissage. Celle-ci avait été "
    "construite à la place de l'Hôtel Dieu de la ville, démoli en 1905. "
    "Aujourd'hui, dans l'actuel espace musique au sous-sol, on peut encore "
    "voir les caves voûtées de l'Hôtel Dieu."
)
TRUE_WORDS = len(REFERENCE_TEXT.split())

# (a): the composed total may exceed the true word count by at most 30%
# (re-wording slack), never the 10x pile-up of the failing state.
TOTAL_WORD_BUDGET = round(TRUE_WORDS * 1.3)

# (b): a word may repeat at most its true count + 1 times, with a floor
# of 2 — spelled-out numbers ("1925" -> "mille neuf cent vingt-cinq") and
# split compounds legitimately repeat without the reference ever saying
# them, but the observed pile-up repeats words 20+ times.
REPEAT_FLOOR = 2

# (c): the dedup trim may remove at most this many committed words between
# consecutive frames (bounded by the over-commit bound: margin + slack).
BOUNDED_DEDUP = 2

# (d): once a composed line has this many words, its opening must
# persist to the utterance's end.
OPENING_MIN_WORDS = 3


def _load_capture() -> dict:
    if not CAPTURE_PATH.exists():
        raise AssertionError(
            f"Capture {CAPTURE_PATH} is missing — run the slow replay test "
            f"(pytest -m slow tests/test_replay_pipeline.py) to regenerate "
            f"it, and commit the result."
        )
    with open(CAPTURE_PATH, encoding="utf-8") as f:
        return json.load(f)


def _replay_capture(events):
    """Replays capture events through one GhostComposer, honoring reset
    boundaries exactly as the pipeline emitted them.

    Returns a list of per-utterance records:
    {"lines": [composed line per frame],
     "committed_lens": [len(committed) per frame],
     "committed_heads": [committed[0] or None per frame]}
    """
    composer = GhostComposer()
    utterances = []
    lines: list[str] = []
    committed_lens: list[int] = []
    committed_heads: list = []

    def _flush():
        nonlocal lines, committed_lens, committed_heads
        if lines:
            utterances.append(
                {
                    "lines": lines,
                    "committed_lens": committed_lens,
                    "committed_heads": committed_heads,
                }
            )
        lines, committed_lens, committed_heads = [], [], []

    for event in events:
        if event["type"] == "reset":
            _flush()
            composer.reset()
        elif event["type"] == "ghost":
            window = event.get("window")
            window = tuple(window) if window is not None else None
            line = composer.update(event["ghost"], window)
            lines.append(line)
            committed_lens.append(len(composer.committed))
            committed_heads.append(composer.committed[0] if composer.committed else None)
    _flush()
    return utterances


def test_capture_replays_without_duplication():
    capture = _load_capture()
    utterances = _replay_capture(capture["events"])

    assert utterances, "capture contains no ghost frames at all"

    # --- (a) total composed words within the true-word budget ---
    total_words = sum(len(u["lines"][-1].split()) for u in utterances)
    assert total_words <= TOTAL_WORD_BUDGET, (
        f"composed {total_words} words across {len(utterances)} utterances, "
        f"budget is {TOTAL_WORD_BUDGET} (true words {TRUE_WORDS}) — "
        f"the composer is duplicating"
    )

    # --- (b) no word repeated beyond true count + 1 (floor 2) ---
    reference_counts = Counter(_fold(w) for w in REFERENCE_TEXT.split())
    composed_counts = Counter()
    for u in utterances:
        composed_counts.update(_fold(w) for w in u["lines"][-1].split())
    for word, count in composed_counts.items():
        cap = max(reference_counts.get(word, 0) + 1, REPEAT_FLOOR)
        assert count <= cap, (
            f"word {word!r} composed {count} times (cap {cap}) — "
            f"the composer is duplicating"
        )

    # --- (c) append-only within an utterance ---
    for u in utterances:
        prev = 0
        for committed_len in u["committed_lens"]:
            assert committed_len >= prev - BOUNDED_DEDUP, (
                f"committed shrank from {prev} to {committed_len} words "
                f"beyond the bounded dedup ({BOUNDED_DEDUP})"
            )
            prev = committed_len

    # --- (d) opening words preserved per utterance ---
    # The model re-words its live text freely (accent and spelling
    # variants: 'médiathèque' -> 'Mediathèque' -> 'Diatèque'), so the
    # opening is preserved structurally: the composed line's head word
    # never changes once established, and committed text — which carries
    # the aged-out opening — is immutable (append-only head).
    for u in utterances:
        head_word = None
        committed_head = None
        for line, committed_head_now in zip(u["lines"], u["committed_heads"]):
            words = [_fold(w) for w in line.split()]
            if head_word is None and len(words) >= OPENING_MIN_WORDS:
                head_word = words[0]
            if head_word is not None:
                assert words[0] == head_word, (
                    f"line head word {head_word!r} changed to {words[0]!r} "
                    f"mid-utterance ({line!r}) — the opening was rewritten"
                )
            if committed_head is None and committed_head_now is not None:
                committed_head = committed_head_now
            elif committed_head is not None:
                # The trim removes from the committed tail only: the head
                # may vanish entirely (bounded dedup — the live tail
                # re-shows the word), but it may never change to a
                # different word.
                if committed_head_now is None:
                    committed_head = None
                else:
                    assert committed_head_now == committed_head, (
                        f"committed head {committed_head!r} changed to "
                        f"{committed_head_now!r} — committed text was rewritten"
                    )


def test_capture_header_snapshot():
    """The capture header records the performance profile, device, and
    weights card the ghosts were produced under (the frozen signal's
    provenance — ADR 0014 adds the weights tag to the header)."""
    capture = _load_capture()
    header = capture["header"]
    for key in (
        "tier",
        "ghost_window_s",
        "ghost_throttle_ms",
        "ghost_padding_s",
        "device",
    ):
        assert key in header, f"capture header missing {key}"
    assert header["ghost_window_s"] > 0
    # The weights tag rides with every NEW capture; the committed fixture
    # predates it (optional here, required for regressions going forward).
    if "weights" in header:
        assert header["weights"] in (
            "fp32 v3",
            "parakeet-redux int4 MatMulNBits",
        )
